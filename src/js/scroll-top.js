/**
 * ===========================================================
 *  Отключаем восстановление позиции скролла при перезагрузке.
 *
 *  Зачем: по умолчанию браузер запоминает, где пользователь остановился,
 *  и после F5 возвращает его туда же. На лендинге это выглядит как баг —
 *  читатель уходил в блок «Услуги и цены», нажимал F5 и снова оказывался
 *  в середине страницы вместо начала.
 *
 *  Файл подключается синхронно в <head>, чтобы сработать до того, как
 *  браузер восстановит позицию. Отдельный файл, а не инлайн-скрипт:
 *  в netlify.toml стоит CSP со script-src 'self' без 'unsafe-inline',
 *  поэтому inline-код там просто заблокируется.
 *
 *  Прямые ссылки вида site.com#faq продолжают работать: если в адресе
 *  есть якорь, скролл не трогаем — сюда пришли намеренно.
 * ===========================================================
 */
(function () {
  'use strict';

  // 'manual' — браузер не будет сам возвращать нас на прошлую позицию.
  // Ставим до проверки якоря: переход по якорю — это fragment navigation,
  // он отрабатывает независимо от scrollRestoration, так что прямые ссылки
  // site.com#faq продолжат работать.
  if ('scrollRestoration' in history) {
    history.scrollRestoration = 'manual';
  }

  // Пришли по ссылке с якорем — не мешаем, пусть браузер сам прокрутит.
  if (window.location.hash && window.location.hash !== '#') return;

  var scrollUp = function () {
    // 'instant' вместо 'smooth': на загрузке страницы анимация выглядит
    // как рывок. Поддерживается не везде — поэтому с запасным вариантом.
    if (typeof window.scrollTo === 'function') {
      try {
        window.scrollTo({ top: 0, left: 0, behavior: 'instant' });
        return;
      } catch (err) {
        /* браузер не знает объектных опций — пробуем по-старому */
      }
      window.scrollTo(0, 0);
    }
  };

  scrollUp();

  // Страница может дорисоваться уже после первого вызова (шрифты, картинки),
  // поэтому повторяем после загрузки — это дёшево и гарантирует верх.
  window.addEventListener('load', scrollUp);
})();
